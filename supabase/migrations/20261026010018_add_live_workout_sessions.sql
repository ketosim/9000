begin;

-- One live performance of an assigned workout.
--
-- A session can be completed by the client independently or recorded by the
-- coach while attending the session.
create table public.workout_sessions (
  id uuid primary key default gen_random_uuid(),

  client_id uuid not null,
  assigned_workout_id uuid not null,

  session_mode text not null default 'client_self',
  status text not null default 'in_progress',

  started_by uuid not null,
  attending_coach_id uuid,

  started_at timestamptz not null default now(),
  completed_at timestamptz,
  abandoned_at timestamptz,

  session_notes text not null default '',

  -- Generated by the browser before starting a session. Reusing the same key
  -- safely returns the existing session instead of creating a duplicate.
  client_request_id uuid not null,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint workout_sessions_client_fkey
    foreign key (client_id)
    references public.profiles(id)
    on delete restrict,

  constraint workout_sessions_workout_fkey
    foreign key (assigned_workout_id)
    references public.assigned_template_workouts(id)
    on delete restrict,

  constraint workout_sessions_started_by_fkey
    foreign key (started_by)
    references public.profiles(id)
    on delete restrict,

  constraint workout_sessions_coach_fkey
    foreign key (attending_coach_id)
    references public.profiles(id)
    on delete restrict,

  constraint workout_sessions_mode_check
    check (
      session_mode in ('client_self', 'coach_attended')
    ),

  constraint workout_sessions_status_check
    check (
      status in ('in_progress', 'completed', 'abandoned')
    ),

  constraint workout_sessions_mode_actor_check
    check (
      (
        session_mode = 'client_self'
        and attending_coach_id is null
      )
      or
      (
        session_mode = 'coach_attended'
        and attending_coach_id is not null
      )
    ),

  constraint workout_sessions_completion_check
    check (
      (
        status = 'in_progress'
        and completed_at is null
        and abandoned_at is null
      )
      or
      (
        status = 'completed'
        and completed_at is not null
        and abandoned_at is null
      )
      or
      (
        status = 'abandoned'
        and completed_at is null
        and abandoned_at is not null
      )
    ),

  constraint workout_sessions_time_check
    check (
      completed_at is null
      or completed_at >= started_at
    ),

  constraint workout_sessions_abandoned_time_check
    check (
      abandoned_at is null
      or abandoned_at >= started_at
    ),

  constraint workout_sessions_notes_check
    check (char_length(session_notes) <= 5000),

  constraint workout_sessions_request_unique
    unique (client_id, client_request_id)
);

create index workout_sessions_client_id_idx
  on public.workout_sessions (client_id);

create index workout_sessions_workout_id_idx
  on public.workout_sessions (assigned_workout_id);

create index workout_sessions_status_idx
  on public.workout_sessions (client_id, status);

create index workout_sessions_started_at_idx
  on public.workout_sessions (client_id, started_at desc);

-- A client may only have one unfinished performance of a particular assigned
-- workout. They can complete the workout again later as a separate session.
create unique index workout_sessions_one_open_workout_idx
  on public.workout_sessions (
    client_id,
    assigned_workout_id
  )
  where status = 'in_progress';


-- Exercises performed during a live session.
--
-- Prescribed exercises point to their assigned snapshot. Ad-hoc exercises do
-- not. A substitute exercise may identify the prescribed exercise it replaced.
create table public.workout_session_exercises (
  id uuid primary key default gen_random_uuid(),

  session_id uuid not null,
  assigned_exercise_id uuid,
  replaces_assigned_exercise_id uuid,

  exercise_source text not null default 'prescribed',

  name text not null,
  position integer not null,

  variation text not null default '',
  side text not null default 'both',
  load_convention text not null default 'total',
  load_unit text not null default 'kg',

  is_deload boolean not null default false,
  exercise_notes text not null default '',

  client_request_id uuid not null,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint session_exercises_session_fkey
    foreign key (session_id)
    references public.workout_sessions(id)
    on delete cascade,

  constraint session_exercises_assigned_exercise_fkey
    foreign key (assigned_exercise_id)
    references public.assigned_template_exercises(id)
    on delete set null,

  constraint session_exercises_replaced_exercise_fkey
    foreign key (replaces_assigned_exercise_id)
    references public.assigned_template_exercises(id)
    on delete set null,

  constraint session_exercises_source_check
    check (
      exercise_source in (
        'prescribed',
        'substitute',
        'additional'
      )
    ),

  constraint session_exercises_source_reference_check
    check (
      (
        exercise_source = 'prescribed'
        and assigned_exercise_id is not null
        and replaces_assigned_exercise_id is null
      )
      or
      (
        exercise_source = 'substitute'
        and assigned_exercise_id is null
        and replaces_assigned_exercise_id is not null
      )
      or
      (
        exercise_source = 'additional'
        and assigned_exercise_id is null
        and replaces_assigned_exercise_id is null
      )
    ),

  constraint session_exercises_name_check
    check (
      char_length(btrim(name)) between 1 and 100
    ),

  constraint session_exercises_position_check
    check (position between 1 and 100),

  constraint session_exercises_side_check
    check (
      side in ('both', 'alternating', 'each_side')
    ),

  constraint session_exercises_load_convention_check
    check (
      load_convention in (
        'total',
        'per_dumbbell',
        'added_plates',
        'machine_display',
        'assistance',
        'bodyweight'
      )
    ),

  constraint session_exercises_load_unit_check
    check (load_unit = 'kg'),

  constraint session_exercises_notes_check
    check (char_length(exercise_notes) <= 2000),

  constraint session_exercises_position_unique
    unique (session_id, position),

  constraint session_exercises_request_unique
    unique (session_id, client_request_id)
);

create index session_exercises_session_id_idx
  on public.workout_session_exercises (session_id);

create index session_exercises_assigned_id_idx
  on public.workout_session_exercises (assigned_exercise_id);

create index session_exercises_replacement_idx
  on public.workout_session_exercises (replaces_assigned_exercise_id);


-- Actual results recorded for each performed set.
--
-- Prescribed sets reference the assigned snapshot. Extra sets and sets for
-- substitute/additional exercises have no prescribed-set reference.
create table public.workout_session_sets (
  id uuid primary key default gen_random_uuid(),

  session_exercise_id uuid not null,
  assigned_set_id uuid,

  set_number integer not null,
  set_source text not null default 'prescribed',

  actual_reps integer,
  actual_load numeric(8,2),
  actual_rir integer,

  side text,
  completed boolean not null default false,
  completed_at timestamptz,

  set_notes text not null default '',

  -- Required for idempotent offline writes.
  client_request_id uuid not null,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint session_sets_exercise_fkey
    foreign key (session_exercise_id)
    references public.workout_session_exercises(id)
    on delete cascade,

  constraint session_sets_assigned_set_fkey
    foreign key (assigned_set_id)
    references public.assigned_template_sets(id)
    on delete set null,

  constraint session_sets_source_check
    check (
      set_source in ('prescribed', 'additional')
    ),

  constraint session_sets_source_reference_check
    check (
      (
        set_source = 'prescribed'
        and assigned_set_id is not null
      )
      or
      (
        set_source = 'additional'
        and assigned_set_id is null
      )
    ),

  constraint session_sets_number_check
    check (set_number between 1 and 100),

  constraint session_sets_reps_check
    check (
      actual_reps is null
      or actual_reps between 0 and 10000
    ),

  constraint session_sets_load_check
    check (
      actual_load is null
      or actual_load >= 0
    ),

  constraint session_sets_rir_check
    check (
      actual_rir is null
      or actual_rir between 0 and 10
    ),

  constraint session_sets_side_check
    check (
      side is null
      or side in ('both', 'left', 'right')
    ),

  constraint session_sets_completion_check
    check (
      (
        completed = false
        and completed_at is null
      )
      or
      (
        completed = true
        and completed_at is not null
      )
    ),

  constraint session_sets_notes_check
    check (char_length(set_notes) <= 2000),

  constraint session_sets_number_unique
    unique (session_exercise_id, set_number),

  constraint session_sets_request_unique
    unique (session_exercise_id, client_request_id)
);

create index session_sets_exercise_id_idx
  on public.workout_session_sets (session_exercise_id);

create index session_sets_assigned_set_id_idx
  on public.workout_session_sets (assigned_set_id);

create index session_sets_completed_idx
  on public.workout_session_sets (
    session_exercise_id,
    completed
  );


comment on table public.workout_sessions is
  'Live client workout performances in either self-training or coach-attended mode.';

comment on column public.workout_sessions.client_request_id is
  'Browser-generated idempotency key used to prevent duplicate session creation during retries or offline synchronisation.';

comment on table public.workout_session_exercises is
  'Prescribed, substitute and additional exercises performed during a live workout session.';

comment on table public.workout_session_sets is
  'Actual reps, load, RIR and completion state recorded during a live workout session.';

comment on column public.workout_session_sets.client_request_id is
  'Browser-generated idempotency key used to prevent duplicate set writes during retries or offline synchronisation.';


-- These tables are never accessed directly by browser clients. Subsequent
-- security-definer RPCs provide narrowly scoped client and coach operations.
alter table public.workout_sessions
  enable row level security;

alter table public.workout_session_exercises
  enable row level security;

alter table public.workout_session_sets
  enable row level security;

revoke all on table public.workout_sessions
  from public, anon, authenticated;

revoke all on table public.workout_session_exercises
  from public, anon, authenticated;

revoke all on table public.workout_session_sets
  from public, anon, authenticated;

grant select, insert, update, delete
  on table public.workout_sessions
  to service_role;

grant select, insert, update, delete
  on table public.workout_session_exercises
  to service_role;

grant select, insert, update, delete
  on table public.workout_session_sets
  to service_role;

commit;